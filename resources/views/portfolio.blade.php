  function filterPortfolio(category, clickedButton) {
    // 1. Update filter tab button styles
    const buttons = document.querySelectorAll('.portfolio-filter-btn');
    buttons.forEach(btn => {
      btn.classList.remove('bg-secondary', 'text-on-secondary', 'shadow-sm');
      btn.classList.add('bg-surface-container', 'text-on-surface-variant');
    });

    clickedButton.classList.remove('bg-surface-container', 'text-on-surface-variant');
    clickedButton.classList.add('bg-secondary', 'text-on-secondary', 'shadow-sm');

    // 2. Filter portfolio cards
    const cards = document.querySelectorAll('.portfolio-card');
    let visibleCount = 0;

    cards.forEach(card => {
      const cardCategory = card.getAttribute('data-category');
      if (category === 'all' || cardCategory === category) {
        card.style.display = 'flex';
        visibleCount++;
      } else {
        card.style.display = 'none';
      }
    });

    // 3. Update counter and empty state
    const counterElem = document.getElementById('visible-count');
    if (counterElem) {
      counterElem.innerText = visibleCount;
    }

    const emptyState = document.getElementById('no-results-msg');
    if (emptyState) {
      if (visibleCount === 0) {
        emptyState.classList.remove('hidden');
        emptyState.classList.add('flex');
      } else {
        emptyState.classList.add('hidden');
        emptyState.classList.remove('flex');
      }
    }
  }
</script>
